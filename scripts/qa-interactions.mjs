// Run after npm run build with the local server running. All AI requests are
// intercepted; these checks do not consume provider credits or send questions.
import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';

const origin = process.env.PORTFOLIO_QA_URL || 'http://127.0.0.1:4173';
const browser = await chromium.launch({headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome'});
try {
  const page = await browser.newPage({viewport: {width: 1280, height: 850}, reducedMotion: 'reduce'});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  let available = false;
  let failNext = false;
  let billingNext = false;
  const payloads = [];
  const requestStates = [];
  await page.route('**/api/**', route => route.fulfill({status: 503, json: {error: 'Disabled during interaction QA.', trackingDisabled: true, recorded: false}}));
  await page.route('**/api/chat/status', route => route.fulfill({json: {available}}));
  await page.route('**/api/chat', async route => {
    requestStates.push(await page.locator('#chat-dialog').getAttribute('data-ai-state'));
    const payload = route.request().postDataJSON();
    payloads.push(payload);
    assert.ok(payload.messages.length <= 11);
    assert.equal(payload.messages.at(-1).role, 'user');
    assert.ok(payload.messages.every(message => message.content.length <= 2000));
    assert.ok(payload.messages.reduce((sum, message) => sum + message.content.length, 0) <= 11000);
    assert.ok(new TextEncoder().encode(JSON.stringify(payload)).byteLength <= 23000);
    payload.messages.forEach((message, index) => assert.equal(message.role, index % 2 ? 'assistant' : 'user'));
    if (billingNext) {
      billingNext = false;
      return route.fulfill({status: 503, json: {code: 'billing_required', error: 'AI chat is unavailable because provider credits are exhausted. Contact Evan directly.'}});
    }
    if (failNext) {
      failNext = false;
      return route.fulfill({status: 502, json: {error: 'Unavailable'}});
    }
    await route.fulfill({json: {reply: 'I build security systems. <img src=x onerror=alert(1)> ' + 'Security '.repeat(350)}});
  });
  await page.goto(origin+'/projects.html');
  await page.waitForFunction(() => document.documentElement.dataset.navigationState === 'idle');
  assert.equal(new URL(page.url()).pathname,'/projects.html');
  assert.equal(await page.locator('main #background,main #credentials,main #about,main #home').count(),0);
  assert.equal(await page.locator('.project-card').count(), 6);
  await page.locator('[data-filter="web"]').click();
  assert.equal(await page.locator('.project-card:visible').count(), 3);
  await page.locator('[data-filter="worlds"]').click();
  assert.equal(await page.locator('.project-card:visible').count(), 3);
  await page.locator('[data-filter="all"]').click();
  await page.locator('.terminal-launch').first().click();
  const input = page.locator('#terminal-input');
  const command = async value => {await input.fill(value); await input.press('Enter');};
  await command('cat education');
  const education = await page.locator('#terminal-output').innerText();
  assert.ok(education.includes('Expected December 2028') && education.includes('Completed May 2025'));
  await input.fill('unfinished draft');
  await input.press('ArrowUp');
  assert.equal(await input.inputValue(), 'cat education');
  await input.press('ArrowDown');
  assert.equal(await input.inputValue(), 'unfinished draft');
  await input.press('Control+l');
  assert.equal(await page.locator('#terminal-output').innerText(), '');
  await command('help');
  const help = await page.locator('#terminal-output>div').last().innerText();
  assert.equal(/\b(?:nano|rm|rmdir|touch|mkdir|echo|cp|mv|sudo|su|head|tail|wc|grep|find|tree|sort|printf)\b/.test(help), false);
  await command('pwd');
  assert.equal(await page.locator('#terminal-output>div').last().innerText(), '/home/visitor');
  await command('mkdir -p notes/browser-check');
  await command('echo "<img src=x onerror=alert(1)>" > notes/browser-check/raw.txt');
  await command('cat notes/browser-check/raw.txt');
  assert.ok((await page.locator('#terminal-output>div').last().innerText()).includes('<img'));
  assert.equal(await page.locator('#terminal-output img').count(), 0);
  await command('cp notes/browser-check/raw.txt notes/browser-check/copy.txt');
  await command('mv notes/browser-check/copy.txt notes/browser-check/edit.txt');
  await command('nano notes/browser-check/edit.txt');
  await page.locator('#nano-dialog[open]').waitFor();
  await page.locator('#nano-content').fill('Saved from the editor.\nA second line.');
  await page.locator('#nano-content').press('Control+o');
  await page.locator('#nano-status').filter({hasText: 'Saved in this browser'}).waitFor();
  await page.locator('#nano-content').press('Control+x');
  await page.locator('#terminal-dialog[open]').waitFor();
  await command('cat notes/browser-check/edit.txt');
  assert.equal(await page.locator('#terminal-output>div').last().innerText(), 'Saved from the editor.\nA second line.');
  await command('head -n 1 notes/browser-check/edit.txt');
  assert.equal((await page.locator('#terminal-output>div').last().innerText()).trim(), 'Saved from the editor.');
  await command('grep -n editor notes/browser-check/edit.txt');
  assert.equal((await page.locator('#terminal-output>div').last().innerText()).trim(), '1:Saved from the editor.');
  await command('wc -w notes/browser-check/edit.txt');
  assert.match((await page.locator('#terminal-output>div').last().innerText()).trim(), /^7 /);
  await command('printf "pear\\napple\\npear\\n" | sort | uniq -c');
  assert.match(await page.locator('#terminal-output>div').last().innerText(), /1 apple\n\s+2 pear/);
  await command('find notes/browser-check -name "edit.*"');
  assert.equal((await page.locator('#terminal-output>div').last().innerText()).trim(), '/home/visitor/notes/browser-check/edit.txt');
  await command('whoami');
  assert.equal(await page.locator('#terminal-output>div').last().innerText(), 'visitor');
  await command('nano notes/browser-check/edit.txt');
  await page.locator('#nano-content').fill('Unsaved changes');
  await page.locator('#nano-content').press('Control+x');
  await page.locator('.nano-unsaved:not([hidden])').waitFor();
  await page.locator('#nano-keep').click();
  await page.locator('#nano-cancel').click();
  await page.locator('#terminal-dialog[open]').waitFor();
  await page.reload();
  await page.waitForFunction(() => document.documentElement.dataset.navigationState === 'idle');
  await page.locator('.terminal-launch').first().click();
  await command('cat notes/browser-check/edit.txt');
  assert.equal(await page.locator('#terminal-output>div').last().innerText(), 'Saved from the editor.\nA second line.');
  // Page commands must navigate to actual documents without losing the
  // visitor's browser-local shell workspace or breaking shared controls.
  await command('experience');
  await page.waitForURL('**/experience.html');
  await page.waitForFunction(() => document.documentElement.dataset.navigationState === 'idle');
  assert.equal(await page.locator('#background').count(),1);
  assert.equal(await page.locator('main #work').count(),0);
  await page.locator('.terminal-launch').first().click();
  await command('cat notes/browser-check/edit.txt');
  assert.equal(await page.locator('#terminal-output>div').last().innerText(), 'Saved from the editor.\nA second line.');
  await command('about');
  await page.waitForURL('**/about.html');
  await page.waitForFunction(() => document.documentElement.dataset.navigationState === 'idle');
  assert.equal(await page.locator('main #about').count(),1);
  await page.locator('.terminal-launch').first().click();
  await command('credentials');
  await page.waitForURL('**/credentials.html');
  await page.waitForFunction(() => document.documentElement.dataset.navigationState === 'idle');
  assert.equal(await page.locator('.document-card').count(),11);
  await page.locator('.terminal-launch').first().click();
  await command('projects');
  await page.waitForURL('**/projects.html');
  await page.waitForFunction(() => document.documentElement.dataset.navigationState === 'idle');
  await page.locator('.terminal-launch').first().click();
  await command('rm -r notes/browser-check');
  assert.match(await page.locator('#terminal-output>div').last().innerText(), /Command not available with these permissions/);
  await command('cat notes/browser-check/edit.txt');
  assert.equal(await page.locator('#terminal-output>div').last().innerText(), 'Saved from the editor.\nA second line.');
  await command('sudo su -');
  assert.match(await page.locator('#terminal-output>div').last().innerText(), /sudo: Command not available with these permissions/);
  await command('su -');
  assert.match(await page.locator('#terminal-output>div').last().innerText(), /su: Command not available with these permissions/);
  await command('rm -rf /');
  assert.match(await page.locator('#terminal-output>div').last().innerText(), /rm: Command not available with these permissions/);
  await command('cat README.txt');
  assert.ok((await page.locator('#terminal-output>div').last().innerText()).includes('visitor workspace'));
  await command('clear');
  await command('ls projects');
  assert.equal(await page.locator('#terminal-output .terminal-action').count(), 6);
  await input.fill('open sta');
  await input.press('Tab');
  assert.equal(await input.inputValue(), 'open starlight');
  await input.press('Enter');
  assert.equal(await page.locator('#project-dialog .button-primary').getAttribute('href'), 'https://starlight-fishing.web.app');
  await page.locator('#project-dialog .dialog-close').click();
  await page.locator('.terminal-launch').first().click();
  await command('open seas');
  assert.equal(await page.locator('#project-dialog .button-primary').getAttribute('href'), 'https://github.com/evanbartkowski/Seven-Seas-Game');
  await page.locator('#project-dialog .dialog-close').click();
  await page.locator('.terminal-launch').first().click();
  await command('chat');
  await page.locator('#chat-status').filter({hasText: 'currently unavailable'}).waitFor();
  assert.equal(await page.locator('#chat-form button[type=submit]').isDisabled(), true);
  available = true;
  await page.locator('#chat-reconnect').click();
  await page.locator('#chat-status').filter({hasText: 'ready'}).waitFor();
  const ask = async (question, answerCount) => {
    await page.locator('#chat-input').fill(question);
    await page.locator('#chat-input').press('Enter');
    await page.waitForFunction(count => document.querySelectorAll('.chat-message-assistant').length === count, answerCount);
  };
  await ask('What do you build?', 1);
  assert.equal(await page.locator('#chat-dialog').getAttribute('data-ai-state'), 'responding');
  assert.equal(await page.locator('.ai-orbits').evaluate(element => getComputedStyle(element).animationName), 'none');
  assert.equal(await page.locator('.chat-message-assistant img').count(), 0);
  assert.ok((await page.locator('.chat-message-assistant').innerText()).includes('<img'));
  await ask('What about AI?', 2);
  assert.equal(payloads[1].messages.length, 3);
  // Longer conversations and Unicode remain within the API limits, including
  // when model responses are longer than a single accepted history message.
  for (let turn = 3; turn <= 8; turn++) await ask('Tell me about your projects. ' + '🌊'.repeat(450), turn);
  failNext = true;
  await page.locator('#chat-input').fill('Retry this question');
  await page.locator('#chat-input').press('Enter');
  await page.locator('.chat-error button').waitFor();
  assert.equal(await page.locator('#chat-dialog').getAttribute('data-ai-state'), 'idle');
  await page.locator('.chat-error button').click();
  await page.waitForFunction(() => document.querySelectorAll('.chat-message-assistant').length === 9);
  assert.equal(await page.locator('.chat-message-user').count(), 9);
  billingNext = true;
  await page.locator('#chat-input').fill('One more question');
  await page.locator('#chat-input').press('Enter');
  await page.locator('#chat-status').filter({hasText: 'credits are exhausted'}).waitFor();
  assert.equal(await page.locator('#chat-dialog').getAttribute('data-ai-state'), 'idle');
  assert.ok((await page.locator('.chat-error').innerText()).includes('credits are exhausted'));
  await page.locator('#chat-dialog .dialog-close').click();
  await page.locator('.terminal-launch').first().click();
  await command('ask Tell me about CyberMaxx');
  await page.waitForFunction(() => document.querySelectorAll('.chat-message-assistant').length === 10);
  assert.equal(await page.locator('dialog[open]').count(), 1);
  await page.setViewportSize({width: 390, height: 844});
  assert.equal(await page.locator('#chat-dialog').evaluate(dialog => dialog.scrollWidth <= dialog.clientWidth), true);
  assert.equal(await page.locator('#chat-form button[type=submit]').isVisible(), true);
  assert.equal(await page.locator('#chat-dialog .dialog-close').isVisible(), true);
  await page.locator('#chat-dialog .dialog-close').click();
  await page.locator('.terminal-launch').first().click();
  await command('nano notes/mobile.txt');
  await page.locator('#nano-content').fill('Mobile editing works.');
  assert.equal(await page.locator('#nano-save').isVisible(), true);
  assert.equal(await page.locator('#nano-dialog').evaluate(dialog => dialog.scrollWidth <= dialog.clientWidth), true);
  await page.locator('#nano-save').click();
  await page.locator('#nano-done').click();
  await page.locator('#terminal-dialog[open]').waitFor();
  await command('rm notes/mobile.txt');
  assert.match(await page.locator('#terminal-output>div').last().innerText(), /Command not available with these permissions/);
  await command('cat notes/mobile.txt');
  assert.equal(await page.locator('#terminal-output>div').last().innerText(), 'Mobile editing works.');

  const fallback = await browser.newPage({viewport: {width: 390, height: 844}, reducedMotion: 'no-preference'});
  fallback.on('pageerror', error => errors.push(error.message));
  await fallback.route('**/api/**', route => route.fulfill({status: 503, json: {error: 'Disabled during interaction QA.', trackingDisabled: true, recorded: false}}));
  await fallback.addInitScript(() => {
    localStorage.setItem('vault-motion', 'paused');
    const original = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function(type, ...args) {return String(type).includes('webgl') ? null : original.call(this, type, ...args);};
  });
  await fallback.goto(origin);
  await fallback.locator('#reactor svg').waitFor();
  assert.equal(await fallback.locator('body').evaluate(body => body.classList.contains('motion-paused')), false);
  await fallback.locator('.terminal-launch').first().click();
  await fallback.locator('#terminal-input').fill('cat about');
  await fallback.locator('#terminal-input').press('Enter');
  assert.ok((await fallback.locator('#terminal-output').innerText()).includes('CyberMaxx'));
  assert.deepEqual(errors, []);
  assert.ok(requestStates.every(state => state === 'thinking'));
  console.log(JSON.stringify({result: 'passed', projects: 6, filters: '3 web / 3 worlds', routing: 'terminal page commands navigate between actual documents and preserve browser-local workspace', terminal: 'content, six project links, completion, history, virtual files, nano, persistence, text filters, pipelines, rm/sudo/su permission denial preserves files, safe text, hidden commands, mobile', chat: 'availability, bounded follow-ups, error/retry, billing, actual thinking/responding/idle states, reduced motion', rendering: 'WebGL fallback and ignored legacy pause preference', mockedChatRequests: payloads.length, pageErrors: errors}));
} finally {
  await browser.close();
}
