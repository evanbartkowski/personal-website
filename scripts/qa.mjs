import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const artifacts = resolve('.artifacts');
await mkdir(artifacts, {recursive: true});
const executablePath = process.env.CHROME_PATH || join(process.env.LOCALAPPDATA, 'ms-playwright/chromium-1243/chrome-win64/chrome.exe');
const browser = await chromium.launch({executablePath, headless:true, args:['--enable-unsafe-swiftshader']});
const base = 'http://127.0.0.1:4173';
const errors = [];
const failures = [];
const page = await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
page.on('pageerror', error => errors.push(error.message));
page.on('response', response => {if (response.status() >= 400) failures.push(`${response.status()} ${response.url()}`);});
try {
  await page.goto(base, {waitUntil:'networkidle'});
  await page.locator('#reactor canvas').waitFor();
  await page.evaluate(() => document.fonts.ready);
  assert.equal(await page.title(), 'Evan Bartkowski — Cybersecurity Engineer & Developer');
  assert.equal(await page.locator('.project-card').count(), 4);
  assert.equal(await page.locator('[data-profile="email"]').first().getAttribute('href'), 'mailto:evan.bartkowski@icloud.com');
  const sourceResume = await readFile('assets/Evan-Bartkowski-Resume.pdf');
  const pdfResponse = await page.request.get(`${base}/assets/Evan-Bartkowski-Resume.pdf`);
  assert.equal(pdfResponse.status(),200);
  assert.match(pdfResponse.headers()['content-type'],/application\/pdf/);
  assert.deepEqual(await pdfResponse.body(),sourceResume,'served resume must match source PDF');
  const downloadEvent = page.waitForEvent('download');
  await page.locator('.hero-ctas [data-profile="resume"]').click();
  const download = await downloadEvent;
  assert.equal(download.suggestedFilename(),'Evan-Bartkowski-Resume.pdf');
  assert.deepEqual(await readFile(await download.path()),sourceResume,'downloaded PDF must match supplied file');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'desktop horizontal overflow');
  await page.screenshot({path:join(artifacts,'desktop.png')});
  for (const section of ['#work','#about','#background','#toolkit','#contact']) {
    await page.locator(section).scrollIntoViewIfNeeded();
  }
  await page.evaluate(() => document.querySelectorAll('.reveal').forEach(item=>item.classList.add('visible')));
  await page.evaluate(() => {document.activeElement?.blur(); scrollTo({top:0,behavior:'instant'});});
  await page.waitForTimeout(850);
  await page.screenshot({path:join(artifacts,'desktop-full.png'),fullPage:true});
  await page.locator('[data-filter="web"]').click();
  assert.equal(await page.locator('.project-card:visible').count(), 2);
  await page.locator('[data-filter="worlds"]').click();
  assert.equal(await page.locator('.project-card:visible').count(), 2);
  await page.locator('[data-filter="all"]').click();
  await page.locator('[data-project="mma"]').first().click();
  await page.locator('#project-dialog[open]').waitFor();
  assert.equal(await page.locator('#project-dialog-title').textContent(), 'MMA Cipher');
  assert.equal(await page.locator('#project-dialog .button-primary').getAttribute('href'), 'https://mma-oracle.web.app');
  await page.screenshot({path:join(artifacts,'project-dossier.png')});
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#project-dialog').evaluate(dialog=>dialog.open), false);
  await page.locator('[data-project="rail"]').first().click();
  assert.match(await page.locator('#project-dialog').textContent(), /DEVELOPMENT PROJECT/);
  await page.keyboard.press('Escape');
  await page.keyboard.press('Control+k');
  await page.locator('#terminal-input').fill('help');
  await page.keyboard.press('Enter');
  assert.match(await page.locator('#terminal-output').textContent(), /NAVIGATION/);
  await page.locator('#terminal-input').fill('resume');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#terminal-output a[download]').getAttribute('href'),'/assets/Evan-Bartkowski-Resume.pdf');
  await page.locator('#terminal-input').fill('<img src=x onerror=alert(1)>');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#terminal-output img').count(), 0, 'terminal input must be escaped');
  await page.locator('#terminal-input').fill('secret');
  await page.keyboard.press('Enter');
  assert.match(await page.locator('#terminal-output').textContent(), /PERK UNLOCKED/);
  await page.keyboard.press('ArrowUp');
  assert.equal(await page.locator('#terminal-input').inputValue(),'secret');
  await page.screenshot({path:join(artifacts,'terminal.png')});
  await page.locator('#terminal-input').fill('contact');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#terminal-dialog').evaluate(dialog=>dialog.open),false);
  await page.keyboard.press('Control+k');
  await page.locator('#terminal-input').fill('background');
  await page.keyboard.press('Enter');
  assert.equal(new URL(page.url()).hash, '#background');
  assert.equal(await page.locator('.experience-history').getAttribute('open'),null);
  await page.locator('.experience-history summary').click();
  assert.equal(await page.locator('.timeline-item:visible').count(),4);
  await page.locator('.experience-history summary').click();
  await page.locator('#copy-email').click();
  await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('EMAIL'));
  assert.match(await page.locator('#toast').textContent(), /EMAIL/);
  await page.locator('#motion-toggle').click();
  assert.equal(await page.locator('#motion-toggle').getAttribute('aria-pressed'),'true');
  await page.locator('#reactor-mode').click();
  assert.equal(await page.locator('#reactor-mode').getAttribute('aria-pressed'),'true');
  await page.evaluate(() => document.querySelector('#reactor canvas').dispatchEvent(new Event('webglcontextlost',{cancelable:true})));
  await page.locator('#reactor>svg').waitFor();
  assert.equal(await page.locator('#reactor-mode').isDisabled(),true);
  await page.locator('[data-project="jinx"]').first().click();
  assert.equal(await page.locator('#project-dialog-title').textContent(),'JinxKiss');
  await page.keyboard.press('Escape');
  console.log('Desktop: rendering, all project filters/dossiers, terminal/history/input escaping, contact, motion, and WebGL recovery passed.');

  const mobile = await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true,reducedMotion:'reduce'});
  mobile.on('pageerror', error=>errors.push(`mobile: ${error.message}`));
  await mobile.goto(base,{waitUntil:'networkidle'});
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'mobile horizontal overflow');
  assert.equal(await mobile.locator('#motion-toggle').getAttribute('aria-pressed'),'true','honors reduced motion');
  await mobile.screenshot({path:join(artifacts,'mobile.png')});
  await mobile.locator('.menu-toggle').click();
  assert.equal(await mobile.locator('.menu-toggle').getAttribute('aria-expanded'),'true');
  await mobile.locator('#mobile-nav a[href="#work"]').click();
  assert.equal(await mobile.locator('#mobile-nav').isVisible(),false);
  await mobile.locator('[data-project="hours"]').first().click();
  await mobile.locator('#project-dialog[open]').waitFor();
  assert.equal(await mobile.locator('#project-dialog-title').textContent(),'Small Hours');
  await mobile.locator('#project-dialog .dialog-close').click();
  await mobile.evaluate(() => document.querySelectorAll('.reveal').forEach(item=>item.classList.add('visible')));
  await mobile.evaluate(() => {document.activeElement?.blur(); scrollTo({top:0,behavior:'instant'});});
  await mobile.screenshot({path:join(artifacts,'mobile-full.png'),fullPage:true});
  for (const width of [320,768,1024,1920]) {
    await mobile.setViewportSize({width,height:900});
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true, `overflow at ${width}px`);
  }
  console.log('Responsive: 320/390/768/1024/1920px, navigation, mobile dossier, reduced motion passed.');
  const blocked = await browser.newPage({viewport:{width:1000,height:800}});
  await blocked.route('**/vendor/**',route=>route.abort());
  await blocked.goto(base,{waitUntil:'networkidle'});
  await blocked.locator('#reactor>svg').waitFor();
  assert.equal(await blocked.locator('.project-card').count(),4);
  await blocked.keyboard.press('Control+k');
  assert.equal(await blocked.locator('#terminal-dialog').evaluate(dialog=>dialog.open),true);
  console.log('Dependency failure: SVG display, project content, terminal remain usable.');
  assert.deepEqual(errors,[],'browser JavaScript errors');
  assert.deepEqual(failures,[],'failed asset requests');
  console.log('PASS: No JavaScript errors, broken local assets, or horizontal overflow.');
} finally {await browser.close();}
